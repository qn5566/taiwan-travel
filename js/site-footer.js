const SiteFooter = (() => {
  function language() {
    if (typeof getWebLang === 'function') return getWebLang();
    let stored;
    try { stored = localStorage.getItem('taiwan_travel_lang'); } catch (e) {}
    return new URLSearchParams(window.location.search).get('lang') || stored || 'zh-TW';
  }
  function apply(lang = language(), root = document) {
    lang = lang === 'zh' ? 'zh-TW' : lang;
    const copy = SITE_FOOTER_I18N[lang] || SITE_FOOTER_I18N.en;
    const chrome = lang === 'de' ? {
      footerContactLabel: 'Markenkooperation', footerQuickLinks: 'Direktlinks',
      footerQuickLinkItems: ['Sehenswürdigkeiten', 'Michelin & Bib Gourmand', 'Ausgewählte Cafés', 'Private Taiwan-Touren', 'Inselhüpfen & Meeresschildkröten', 'Bahnreisen', 'Taiwan-Reportagen']
    } : (WEB_CHROME_I18N[lang] || WEB_CHROME_I18N.en);
    const brand = (WEB_I18N[lang] || WEB_I18N.en).brandName;
    root.querySelectorAll('[data-footer-text]').forEach(el => {
      const key = el.dataset.footerText;
      el.textContent = key === 'brand' ? brand : copy[key] || chrome[key] || '';
    });
    root.querySelectorAll('[data-footer-link]').forEach(el => {
      el.textContent = chrome.footerQuickLinkItems[Number(el.dataset.footerLink)];
    });
    root.querySelectorAll('[data-footer-title]').forEach(el => {
      el.title = copy.team + ' · HiMyDream STUDIO';
      el.setAttribute('aria-label', el.title);
    });
  }
  return { apply, language };
})();
document.addEventListener('DOMContentLoaded', () => SiteFooter.apply());
