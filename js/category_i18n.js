const CategoryUI = (() => {
  const cafeFallback = typeof TAIWAN_CAFES_DATA !== 'undefined' ? TAIWAN_CAFES_DATA.slice() : [];
  const featureKeys = { '全部': '全部', '有插頭': 'work', '手沖咖啡': 'pourover', '甜點好吃': 'desserts', '植栽老宅': 'vintage', '採光超好': 'daylight', '海景景觀': 'ocean', '店家可喝酒': 'bar', '適合聊天': 'chat', '寵物友善': 'pet', '小孩友善': 'kid' };
  function lang() {
    const value = typeof getWebLang === 'function' ? getWebLang()
      : new URLSearchParams(window.location.search).get('lang') || document.documentElement.lang;
    return value === 'zh' ? 'zh-TW' : value || 'zh-TW';
  }
  function t(key) {
    const read = dict => key.split('.').reduce((value, part) => value?.[part], dict);
    return read(CATEGORY_I18N[lang()]) || read(CATEGORY_I18N.en) || '';
  }
  function city(name) { return CityRegions.localizedName(name, lang()); }
  function region(id) { return t(`regions.${id}`); }
  function theme(id) { return t(`themeLabels.${id}`); }
  function topic(id) { return t(`topicLabels.${id}`); }
  function feature(tag) { return featureKeys[tag] ? t(`features.${featureKeys[tag]}`) : tag; }

  function applyCafeHero(tab) {
    const kind = tab === 'michelin-guide' || tab === 'michelin' ? 'michelin' : tab === 'weekend-hop' ? 'journals' : 'coffee';
    const title = document.getElementById('hero-main-title');
    const subtitle = document.getElementById('hero-sub-desc');
    if (title) { title.textContent = t(`${kind}.title`); title.dataset.categoryText = `${kind}.title`; }
    if (subtitle) { subtitle.textContent = t(`${kind}.subtitle`); subtitle.dataset.categoryText = `${kind}.subtitle`; }
  }

  function normalizeCafes(data, chinese = cafeFallback) {
    const originals = new Map(chinese.filter(item => item?.id != null).map(item => [String(item.id), item]));
    return data.map(item => {
      const original = originals.get(String(item.id));
      return { ...item, filterCity: (original?.city || item.city || '').replace(/臺/g, '台'), filterTags: original?.tags || item.tags || [] };
    });
  }

  function apply() {
    document.querySelectorAll('[data-category-text]').forEach(node => {
      const text = t(node.dataset.categoryText);
      if (text) node.textContent = text;
    });
    document.querySelectorAll('[data-category-placeholder]').forEach(node => {
      const text = t(node.dataset.categoryPlaceholder);
      if (text) { node.placeholder = text; node.setAttribute('aria-label', text); }
    });
    document.querySelectorAll('[data-category-label]').forEach(node => node.setAttribute('aria-label', t(node.dataset.categoryLabel)));
    if (document.getElementById('hero-main-title')) {
      const tab = typeof currentMainTab !== 'undefined' && currentMainTab !== 'coffee-map'
        ? currentMainTab : new URLSearchParams(window.location.search).get('tab');
      applyCafeHero(tab);
    }
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', apply);
  else apply();
  return { lang, t, city, region, theme, topic, feature, apply, applyCafeHero, normalizeCafes };
})();
